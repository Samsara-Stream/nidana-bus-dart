import 'package:yaml/yaml.dart';

/// The pure generator both the builder and the command entry call.
String generateTopics(String yamlSource) {
  final doc = loadYaml(yamlSource) as YamlMap;
  final names = (doc['topics'] as YamlList).cast<String>();
  final out = StringBuffer('// GENERATED by wl_codegen\nconst topicNames = <String>[\n');
  for (final n in names) {
    out.writeln("  '$n',");
  }
  out.writeln('];');
  return out.toString();
}
